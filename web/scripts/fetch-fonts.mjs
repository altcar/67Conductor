/**
 * Downloads the two OFL webfonts used by the store and writes a local
 * @font-face stylesheet so the app has zero runtime third-party requests.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, "..");
const fontsDir = join(web, "public", "fonts");
const cssPath = join(web, "src", "fonts.css");

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36";

const families = [
  { family: "Space Grotesk", spec: "Space+Grotesk:wght@400;500;600;700", prefix: "space-grotesk" },
  { family: "JetBrains Mono", spec: "JetBrains+Mono:wght@400;500;600", prefix: "jetbrains-mono" },
];

await mkdir(fontsDir, { recursive: true });
let css = "/* Generated by scripts/fetch-fonts.mjs. Fonts: SIL Open Font License 1.1 */\n";

for (const { family, spec } of families) {
  const url = `https://fonts.googleapis.com/css2?family=${spec}&display=swap`;
  const response = await fetch(url, { headers: { "User-Agent": UA } });
  if (!response.ok) throw new Error(`fonts css ${response.status}`);
  let text = await response.text();

  const urls = [...text.matchAll(/url\((https:\/\/[^)]+\.woff2)\)/g)].map((m) => m[1]);
  const unique = [...new Set(urls)];
  let index = 0;
  for (const remote of unique) {
    const data = await fetch(remote, { headers: { "User-Agent": UA } });
    const buffer = Buffer.from(await data.arrayBuffer());
    const name = `${family.toLowerCase().replace(/\s+/g, "-")}-${index}.woff2`;
    await writeFile(join(fontsDir, name), buffer);
    text = text.split(remote).join(`/fonts/${name}`);
    index += 1;
  }
  css += `\n/* ${family} */\n${text.trim()}\n`;
  console.log(`${family}: ${unique.length} woff2 files`);
}

await writeFile(cssPath, css);
console.log("wrote src/fonts.css");
